/** Issuing was refused: nothing was issued and no number used. Messages say why (no invoice content). */
class IssueRejectedException(
    val messages: List<ValidationMessage>,
) : RuntimeException("Invoice not issued: ${messages.joinToString { it.ruleId }}")

/**
 * Issues one invoice (Software Design §5, Flow C), in the worker. In one transaction:
 * 1. lock the draft and the workspace's number counter (`SELECT … FOR UPDATE`), assign the next number;
 * 2. generate the file with invoice-core (XRechnung CII/UBL or ZUGFeRD PDF/A-3);
 * 3. validate it with the active pack (KoSIT, veraPDF, content checks): it must be VALID or WARNING;
 * 4. archive it write-once, create the outgoing document, record the issued invoice, freeze the draft.
 * If step 3 (or the server-side checks) fails, everything rolls back to a savepoint, so the
 * number is not used, and the draft returns to DRAFT with the reasons.
 *
 * Idempotent: an issued draft is left alone; a retry after a crash starts over, and the
 * generated bytes are the same, so the archive stores the original once.
 */
@Component
class IssueInvoiceJobHandler internal constructor(
    private val issuer: InvoiceIssuer,
) : JobHandler<IssueInvoiceJobHandler.Payload> {
    data class Payload(
        val invoiceId: UUID,
        val actorId: UUID?,
    )

    override val type = TYPE
    override val payloadType = Payload::class.java

    override fun handle(
        payload: Payload,
        context: JobContext,
    ) {
        issuer.issue(payload.invoiceId, payload.actorId, finalAttempt = context.attempt >= MAX_ATTEMPTS)
    }

    companion object {
        const val TYPE = "creator.issue-invoice"
        const val MAX_ATTEMPTS = 5
    }
}

/** The issuing transaction itself; also called directly by the concurrency test (CR-03). */
@Component
class InvoiceIssuer internal constructor(
    private val drafts: DraftRepository,
    private val issuedRepo: IssuedRepository,
    private val settingsRepo: InvoiceSettingsRepository,
    private val sequences: NumberSequences,
    private val profiles: WorkspaceProfiles,
    private val validator: ObjectProvider<InvoiceValidator>,
    private val archive: Archive,
    private val documents: Documents,
    private val events: ApplicationEventPublisher,
    private val creator: ObjectProvider<Creator>,
    meters: MeterRegistry,
    transactionManager: PlatformTransactionManager,
    private val clock: Clock = Clock.system(Creator.BERLIN),
) {
    private val log = LoggerFactory.getLogger(javaClass)
    private val rejected = meters.counter("erika.creator.issue.rejected")
    private val issuedCount = meters.counter("erika.creator.issued")
    private val savepoint =
        TransactionTemplate(transactionManager).apply { propagationBehavior = TransactionDefinition.PROPAGATION_NESTED }

    /** Runs in the caller's transaction, scoped to the workspace. Returns the number, or null if not issued. */
    @Transactional(propagation = Propagation.MANDATORY)
    fun issue(
        invoiceId: UUID,
        actorId: UUID?,
        finalAttempt: Boolean = false,
    ): String? {
        val draft = drafts.lock(invoiceId)
        if (draft == null || draft.state != DraftState.ISSUING) return issuedRepo.find(invoiceId)?.number
        return try {
            savepoint.execute { issueLocked(draft, actorId) }
        } catch (e: IssueRejectedException) {
            reject(draft, actorId, e.messages)
            null
        } catch (
            @Suppress("TooGenericExceptionCaught") e: Exception,
        ) {
            if (!finalAttempt) throw e
            log.error("Invoice {} could not be issued after the last attempt; back to draft", invoiceId, e)
            reject(
                draft,
                actorId,
                listOf(
                    message(
                        "ERIKA-ISSUE-FAILED",
                        "Die Rechnung konnte wegen eines technischen Fehlers nicht ausgestellt werden. Bitte versuchen Sie es erneut.",
                    ),
                ),
            )
            null
        }
    }

    private fun issueLocked(
        draft: DraftRow,
        actorId: UUID?,
    ): String {
        val ws = draft.workspaceId
        val settings = settingsRepo.find(ws)
        val seller = profiles.of(ws)
        val problems = DraftChecks.problems(draft.kind, draft.content, settings, seller)
        if (problems.isNotEmpty()) {
            throw IssueRejectedException(
                problems.map {
                    message("ERIKA-DRAFT-${it.code}", "Pflichtangabe fehlt oder ist ungültig: ${it.field}", it.field)
                },
            )
        }
        val original = draft.originalInvoiceId?.let { issuedRepo.find(it) }
        val today = LocalDate.now(clock)
        val issueDate = draft.content.issueDate ?: today
        val format = Creator.formatOf(draft.content, settings)

        val number = sequences.next(ws, settings.patternFor(draft.kind), issueDate, issuedRepo::numberTaken)
        val model =
            InvoiceAssembler.build(
                draft.kind,
                draft.content,
                settings,
                seller,
                number,
                issueDate,
                original?.let { OriginalReference(it.number, it.issueDate) },
            )
        val bytes = InvoiceWriter.write(model, format)
        val report = validator.getObject().validate(bytes, today)
        if (report.level == ValidationLevel.ERROR) throw IssueRejectedException(report.errors)

        val stored = archive.store(ws, bytes, format.mediaType, issueDate, today, actorId)
        val fileName = InvoiceWriter.fileName(model, format)
        val documentId = documents.registerOutgoing(stored, fileName, actorId)
        val prepared = InvoiceWriter.prepare(model, format)
        issuedRepo.insert(
            IssuedRow(
                id = draft.id,
                workspaceId = ws,
                number = number,
                kind = draft.kind,
                typeCode = draft.kind.typeCode,
                format = format,
                documentId = documentId,
                sha256 = stored.sha256,
                fileName = fileName,
                mediaType = format.mediaType,
                originalInvoiceId = original?.id,
                customerId = draft.content.customerId,
                issueDate = issueDate,
                dueDate = prepared.dueDate,
                buyerName = prepared.buyer.name!!,
                buyerEmail =
                    draft.content.buyer.email
                        ?.trim()
                        ?.takeIf { it.isNotEmpty() },
                currency = prepared.currency!!,
                net = prepared.totals.totalWithoutVat!!,
                tax = prepared.totals.totalVat!!,
                gross = prepared.totals.totalWithVat!!,
                issuedBy = actorId,
                issuedAt = java.time.OffsetDateTime.now(clock),
            ),
        )
        drafts.markIssued(draft.id)
        // System invoices (ERIKA's own, ADR 0033) are emailed in the same transaction as the issue.
        draft.sendTo.forEach { creator.getObject().requestSend(ws, actorId, draft.id, it, null, null) }
        if (draft.kind.cancelsOriginal && original != null) {
            documents.changeStatus(ws, original.documentId, DocumentStatus.CANCELLED, "$number", actorId)
        }
        events.publishEvent(
            InvoiceIssued(
                ws,
                actorId,
                draft.id,
                number,
                draft.kind,
                format.name,
                documentId,
                stored.sha256,
                report.level.name,
                report.packId,
            ),
        )
        issuedCount.increment()
        return number
    }

    private fun reject(
        draft: DraftRow,
        actorId: UUID?,
        messages: List<ValidationMessage>,
    ) {
        rejected.increment()
        if (draft.sendTo.isNotEmpty()) {
            // A system invoice that can't be issued needs the operator (alert via the error log).
            log.error("System invoice {} was rejected: {}", draft.id, messages.map { it.ruleId }.distinct())
        }
        drafts.backToDraft(draft.id, messages)
        events.publishEvent(InvoiceIssueRejected(draft.workspaceId, actorId, draft.id, messages.map { it.ruleId }))
    }

    private fun message(
        ruleId: String,
        text: String,
        location: String? = null,
    ) = ValidationMessage(ruleId, MessageSeverity.ERROR, MessageSource.CONTENT, text, null, location)
}
